package com.enterprise.opsassistant.domain;

/**
 * 指标在最近观察窗口中的变化方向。
 *
 * <p>趋势是根因判断的重要补充：数值相同但趋势不同，可能对应正在恶化、正在恢复或长期稳定
 * 三种完全不同的处置策略。</p>
 */
public enum MetricTrend {
    /** 指标正在上升。对错误率、延迟、资源占用等指标通常意味着风险增大。 */
    UP,
    /** 指标正在下降，是否代表恢复需要结合指标含义判断。 */
    DOWN,
    /** 指标在最近窗口内基本稳定。 */
    STABLE,
    /** 没有足够历史数据，暂时无法判断趋势。 */
    UNKNOWN
}
